# OCR用のプロンプト定数定義（文脈・物理レイアウト対応版）

# 共通のベースルール: 叙述の保全性原則 (Narrative Integrity)
BASE_RULES = """【規則】
1. 文章の連結: 前のページや前の行から文章が論理的に続いている場合、物理的なページ境界や改行位置で文章を切断せず、自然に連結してください。
2. 段落の保持: 常に「文頭が一字下がっている」等の物理的な特徴を見て、真に段落が変わる箇所のみで改行してください。
3. 見出しの判定 (Moat & Break):
   - 以下の「物理的な孤立」の兆候がある行を "# " 見出しとして抽出してください。
   - Moat (余白): 上下の行との間に、通常の行間の3倍以上の広い余白がある独立した行。
   - Break (断絶): 縦書きにおいて、行がページの下端まで到達せず、途中で途切れている短い行。
4. ノイズ除去: ページ番号（ノンブル）、ヘッダー（柱）、フッターは叙述を妨げるノイズとして無視してください。
5. 出力形式: 抽出したテキストのみを出力し、挨拶や解説は一切含めないでください。"""

# 前ページの文脈を提示するテンプレート
CONTEXT_ADVISOR = """【前ページの文脈 (Context)】
以下のテキストは、前のページの末尾部分です。現在処理している画像の冒頭が、このテキストから論理的に続いているかを確認し、文脈が通じるように抽出してください。
---
{prev_context}
---
"""

